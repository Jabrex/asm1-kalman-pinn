def sensor_subsets(targets: Sequence[str], candidates: Sequence[str]) -> dict[str, list[str]]:
    subsets = {"drop-%s" % c: [t for t in targets if t != c] for c in targets}
    subsets["drop-DO"] = [t for t in targets if not t.startswith("S_O_")]
    subsets["drop-Nanalysers"] = [t for t in targets if not t.startswith(("S_NH_", "S_NO_"))]
    for c in candidates:
        subsets["add-%s" % c] = [*targets, c]
    return subsets


def sensor_files(candidates: Sequence[str]) -> dict[str, dict]:
    return {
        "grid/sensors/k100_ie_a0_%s" % name: cell("k100_ie_a0_%s" % name, DATA_DIRS["k100"], "k100", "ie", "a0",
                                                  OBSERVER_ROOT, PAIR, TUNED, channels=chans)
        for name, chans in sensor_subsets(DEFAULT_TARGETS, candidates).items()
    }


def grid(stage: str, realistic: str | None = None, rands: Sequence[str] = (), candidates: Sequence[str] = (),
         augment: Sequence[str] = (), smoother: str = "eks") -> dict[str, dict]:
    if stage == "numerics":
        return numerics_files()
    if stage != "grid":
        raise ValueError("stage must be 'numerics' or 'grid', got %r" % stage)
    if realistic not in ("k100", "k050"):
        raise ValueError("realistic must be 'k100' or 'k050', got %r" % realistic)
    if smoother not in ("eks", "ieks"):
        raise ValueError("smoother must be 'eks' or 'ieks', got %r" % smoother)
    files: dict[str, dict] = {}
    files.update(main_files(realistic, augment, smoother))
    files.update(realisation_files())
    files.update(m0prime_files(augment))
    files.update(random_files(rands, augment))
    files.update(sigma_log_files())
    files.update(lab_files(realistic))
    files.update(settler_files())
    files.update(sensor_files(candidates))
    return files


