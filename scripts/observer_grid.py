def write(stage: str, root: Path = OBSERVER_CONFIG_DIR) -> list[Path]:
    files = build(stage)
    needed = sorted({p for c in files.values() for p in (c["data_dir"], c["anchor_file"])})
    missing = [p for p in needed if not (REPO / p).exists()]
    if missing:
        raise FileNotFoundError("inputs missing for the %s stage (%d): %s" % (stage, len(missing), ", ".join(missing[:10])))
    for sub in STAGE_DIRS[stage]:
        for old in (REPO / root / sub).rglob("*.yaml"):
            old.unlink()
    written = []
    for key, cfg in sorted(files.items()):
        path = REPO / root / (key + ".yaml")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER % stage + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        written.append(path)
    return written


def load_stage(stage: str, root: Path = OBSERVER_CONFIG_DIR) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for sub in STAGE_DIRS[stage]:
        for path in sorted((REPO / root / sub).rglob("*.yaml")):
            out[path.relative_to(REPO / root).with_suffix("").as_posix()] = load_cell_config(path)
    if not out:
        raise FileNotFoundError("no %s-stage YAML under %s; run 'write --stage %s' first" % (stage, root, stage))
    return out


def count(stage: str) -> int:
    fams: dict[str, list] = {}
    for key, cfg in load_stage(stage).items():
        fam = key.split("/")[1] if stage == "grid" else key.split("/")[0]
        entry = fams.setdefault(fam, [0, set(), 0])
        entry[0] += 1
        entry[1].add(cfg["cell"])
        entry[2] += len(expected_run_dirs(cfg))
    for fam, (n, cells, runs) in sorted(fams.items()):
        print("%-14s %4d files %4d cells %5d estimator runs" % (fam, n, len(cells), runs))
    print("%-14s %4d files            %5d estimator runs"
          % ("total", sum(e[0] for e in fams.values()), sum(e[2] for e in fams.values())))
    return 0


def available_bytes() -> int | None:
    if sys.platform == "win32":
        import ctypes

        class MemoryStatusEx(ctypes.Structure):
            _fields_ = [("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong),
                        ("ullTotalPhys", ctypes.c_ulonglong), ("ullAvailPhys", ctypes.c_ulonglong),
                        ("ullTotalPageFile", ctypes.c_ulonglong), ("ullAvailPageFile", ctypes.c_ulonglong),
                        ("ullTotalVirtual", ctypes.c_ulonglong), ("ullAvailVirtual", ctypes.c_ulonglong),
                        ("ullAvailExtendedVirtual", ctypes.c_ulonglong)]

        stat = MemoryStatusEx()
        stat.dwLength = ctypes.sizeof(MemoryStatusEx)
        if not ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(stat)):
            return None
        return int(stat.ullAvailPhys)
    try:
        return int(os.sysconf("SC_AVPHYS_PAGES") * os.sysconf("SC_PAGE_SIZE"))
    except (ValueError, OSError, AttributeError):
        return None


def default_workers() -> int:
    avail = available_bytes()
    if avail is None:
        return 8
    return max(1, min(MAX_WORKERS, int((avail - RESERVED_BYTES) // BYTES_PER_WORKER)))


def _registered(allow_drift: str | None) -> bool:
    state, detail = registration_state()
    if state == "ok":
        return True
    if state == "drift" and allow_drift:
        log_deviation(allow_drift, detail, "observer_grid")
        return True
    hint = "" if state == "no_tag" else "; pass --allow-drift REASON to proceed and log it"
    print("REFUSED: %s. The final grid runs only after the pre-registration%s." % (detail, hint))
    return False


def _run_one(key: str, inner_workers: int = 1) -> int:
    path = OBSERVER_CONFIG_DIR / (key + ".yaml")
    cfg = load_cell_config(REPO / path)
    out = REPO / cfg["out_dir"]
    out.mkdir(parents=True, exist_ok=True)
    with open(out / ("run_observers_%s.log" % Path(key).name), "a", encoding="utf-8") as log:
        return subprocess.run(
            [sys.executable, "-m", "scripts.run_observers", "--config", path.as_posix(),
             "--workers", str(inner_workers), "--resume"],
            cwd=REPO, stdout=log, stderr=subprocess.STDOUT, env={**os.environ, **SINGLE_THREAD_ENV},
        ).returncode


def _run_files(keys: list[str], workers: int, inner_workers: int = 1) -> int:
    print("run_observers: %d files on %d workers" % (len(keys), workers), flush=True)
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        codes = dict(zip(keys, pool.map(lambda k: _run_one(k, inner_workers), keys)))
    failed = sorted(k for k, c in codes.items() if c != 0)
    for key in failed:
        print("  EXIT %d  %s (see run_observers_*.log in its out_dir)" % (codes[key], key))
    return 1 if failed else 0


def run(stage: str, family: str | None = None, workers: int | None = None, allow_drift: str | None = None) -> int:
    if stage == "grid" and not _registered(allow_drift):
        return 3
    files = load_stage(stage)
    workers = workers or default_workers()
    if stage == "numerics":
        fam = family or "numerics"
        return _run_files([k for k in files if k.startswith(fam + "/")], workers)
    first = "grid/main/k000_ie_a0"
    code = _run_files([first], 1, inner_workers=6)
    if not (REPO / FROZEN_Q_SOURCE).exists():
        print("STOP: %s was not written; the frozen-q runs cannot start." % FROZEN_Q_SOURCE)
        return 2
    return max(code, _run_files([k for k in files if k != first], workers))


def _baseline_argv(cfg: dict, root: str, rows: Sequence[str]) -> list[str]:
    return ["--data-dir", cfg["data_dir"], "--out", "%s/%s" % (root, cfg["cell"]),
            "--anchor-file", cfg["anchor_file"], "--rows", *rows,
            "--ras-filter-window", str(cfg["ras_filter_window"]), "--influent-mode", cfg["influent_mode"]]


def baseline_jobs(stage: str, files: dict[str, dict]) -> list[list[str]]:
    if stage == "numerics":
        return [_baseline_argv(files["numerics/k100_ic_as"], NUMERICS_BASELINE_ROOT, ("persistence",))]
    seen: dict[str, list[str]] = {}
    for key, cfg in sorted(files.items()):
        family = key.split("/")[1]
        if family in ("main", "m0prime", "sigma_log", "random") and cfg["cell"] not in seen:
            argv = _baseline_argv(cfg, BASELINE_ROOT, BASELINE_ROWS)
            seen[cfg["cell"]] = argv + ["--sigmas", "%.2f" % SIGMA] if family == "random" else argv
    return list(seen.values())


def _baseline_dirs(argv: list[str]) -> list[Path]:
    out = Path(argv[argv.index("--out") + 1])
    rows = argv[argv.index("--rows") + 1: argv.index("--ras-filter-window")]
    return [out / ("%s_sigma%s" % (row, sigma_tag(SIGMA))) for row in rows]


def run_baselines(stage: str, workers: int, allow_drift: str | None = None) -> int:
    if stage == "grid" and not _registered(allow_drift):
        return 3
    todo = [a for a in baseline_jobs(stage, load_stage(stage))
            if not all((REPO / d / "summary.json").exists() for d in _baseline_dirs(a))]
    print("make_baselines: %d invocations pending" % len(todo), flush=True)

    def one(argv: list[str]) -> int:
        out = REPO / argv[argv.index("--out") + 1]
        out.mkdir(parents=True, exist_ok=True)
        with open(out / "make_baselines.log", "a", encoding="utf-8") as log:
            return subprocess.run([sys.executable, "-m", "scripts.make_baselines", *argv], cwd=REPO,
                                  stdout=log, stderr=subprocess.STDOUT,
                                  env={**os.environ, **SINGLE_THREAD_ENV}).returncode

    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        codes = list(pool.map(one, todo))
    failed = [a[a.index("--out") + 1] for a, c in zip(todo, codes) if c != 0]
    for path in failed:
        print("  FAILED make_baselines --out %s (see make_baselines.log)" % path)
    return 1 if failed else 0


def classify_run_dir(run_dir: Path) -> str:
    if (run_dir / "summary.json").exists() and (run_dir / "predictions.npz").exists():
        return "ok"
    return "error" if (run_dir / "error.txt").exists() else "missing"


def numerics_reproduced(files: dict[str, dict]) -> dict[str, int]:
    """Final-grid tuned EKF/EKS at sigma 0.10 must equal the numerics pass bit for bit."""
    same = differ = 0
    for key, cfg in files.items():
        if not key.startswith("grid/main/") or "__" in key:
            continue
        for est in PAIR:
            final = REPO / cfg["out_dir"] / ("%s_sigma0p10" % est) / "predictions.npz"
            pre = REPO / NUMERICS_OBSERVER_ROOT / cfg["cell"] / ("%s_sigma0p10" % est) / "predictions.npz"
            if final.exists() and pre.exists():
                with np.load(final) as a, np.load(pre) as b:
                    if np.array_equal(a["train"], b["train"]):
                        same += 1
                    else:
                        differ += 1
    return {"identical": same, "different": differ}


def status(stage: str) -> int:
    files = load_stage(stage)
    runs = {d.as_posix(): classify_run_dir(REPO / d) for c in files.values() for d in expected_run_dirs(c)}
    base = {d.as_posix(): classify_run_dir(REPO / d) for a in baseline_jobs(stage, files) for d in _baseline_dirs(a)}

    def counts(m: dict[str, str]) -> dict[str, int]:
        return {s: sum(1 for v in m.values() if v == s) for s in ("ok", "error", "missing")}

    report: dict[str, Any] = {"stage": stage, "estimator_runs": counts(runs), "baseline_runs": counts(base),
                              "errors": sorted(k for k, v in {**runs, **base}.items() if v == "error"),
                              "missing": sorted(k for k, v in {**runs, **base}.items() if v == "missing")}
    if stage == "grid":
        report["numerics_reproduced"] = numerics_reproduced(files)
    out = REPO / V11 / ("observer_status_%s.json" % stage)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("estimator runs %s | baseline runs %s%s -> %s" % (
        report["estimator_runs"], report["baseline_runs"],
        " | numerics reproduced %s" % report["numerics_reproduced"] if stage == "grid" else "",
        out.relative_to(REPO).as_posix()))
    return 0 if not report["missing"] else 1


def check_contract_runs(cfg: dict) -> list[str]:
    problems: list[str] = []
    with np.load(REPO / DATA_DIRS["k000"] / "obs_dry_sigma0p10.npz") as data:
        t = np.asarray(data["t"])
    shapes = {"train": (int(np.sum(t <= 12.0 + 1e-9)), 5, 14), "holdout": (int(np.sum(t >= 12.0 - 1e-9)), 5, 14)}
    for run_dir in expected_run_dirs(cfg):
        d = REPO / run_dir
        if not (d / "summary.json").exists():
            problems.append("%s: no summary.json" % run_dir.as_posix())
            continue
        s = json.loads((d / "summary.json").read_text(encoding="utf-8"))
        missing = [k for k in CONTRACT_KEYS if k not in s]
        if missing:
            problems.append("%s: summary lacks %s" % (run_dir.as_posix(), missing))
        if s.get("arch") != "observer" or s.get("model") != run_dir.name.split("_sigma")[0]:
            problems.append("%s: arch/model %r/%r" % (run_dir.as_posix(), s.get("arch"), s.get("model")))
        if run_dir.name.startswith(("ekf_aug", "eks_aug")) and sorted(s.get("learned_multipliers") or {}) != sorted(cfg["augment"]):
            problems.append("%s: learned_multipliers %r" % (run_dir.as_posix(), s.get("learned_multipliers")))
        with np.load(d / "predictions.npz") as p:
            for key, shape in shapes.items():
                if key not in p.files or p[key].shape != shape or not np.isfinite(p[key]).all():
                    problems.append("%s: predictions[%r] missing, wrong shape or non-finite" % (run_dir.as_posix(), key))
    return problems


def contract(inner_workers: int = 1) -> int:
    """One K0-Ie-A0 cell with a single q value, through the real run_observers and collect_runs."""
    from src.eval.report import collect_runs

    root = Path(CONTRACT_ROOT)
    tuned = cell("k000_ie_a0", DATA_DIRS["k000"], "k000", "ie", "a0", root.as_posix(), FULL + ("ieks",), TUNED,
                 augment=kinetic_names())
    tuned["q_grid"] = [0.03]
    frozen = dict(tuned, estimators=["eks"], q_mode=["frozen"], augment=[],
                  frozen_q_from=(root / "k000_ie_a0" / "ekf_sigma0p10" / "summary.json").as_posix())
    problems: list[str] = []
    for name, raw in (("tuned", tuned), ("frozen", frozen)):
        cfg = validate_cell_config(raw, source="contract_" + name)
        path = REPO / root / "configs" / ("%s.yaml" % name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER % "contract" + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        code = subprocess.run([sys.executable, "-m", "scripts.run_observers", "--config", path.as_posix(),
                               "--workers", str(inner_workers), "--resume"], cwd=REPO,
                              env={**os.environ, **SINGLE_THREAD_ENV}).returncode
        if code != 0:
            problems.append("run_observers exit %d on %s" % (code, path.name))
        problems.extend(check_contract_runs(cfg))
    cell_dir = REPO / root / "k000_ie_a0"
    tuned_q = json.loads((cell_dir / "ekf_sigma0p10" / "summary.json").read_text(encoding="utf-8")).get("selected_q")
    frozen_path = cell_dir / "eks_frozenq_sigma0p10" / "summary.json"
    if frozen_path.exists() and json.loads(frozen_path.read_text(encoding="utf-8")).get("selected_q") != tuned_q:
        problems.append("frozen run did not reuse the tuned q %r" % (tuned_q,))
    rows = collect_runs(cell_dir, REPO / DATA_DIRS["k000"])
    if len({r["run_id"] for r in rows}) != 7:
        problems.append("collect_runs scored %d runs, expected 7" % len({r["run_id"] for r in rows}))
    report = {"passed": not problems, "problems": problems}
    (REPO / root / "contract_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("CONTRACT %s%s" % ("PASS" if not problems else "FAIL", "" if not problems else ":\n  " + "\n  ".join(problems)))
    return 0 if not problems else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["write", "count", "run", "baselines", "status", "contract"])
    parser.add_argument("--stage", choices=["numerics", "grid"], default=None)
    parser.add_argument("--family", default=None, help="numerics stage: 'numerics' (default) or 'numerics_ieks'")
    parser.add_argument("--workers", type=int, default=None)
    parser.add_argument("--allow-drift", default=None, metavar="REASON")
    args = parser.parse_args(argv)
    if args.command != "contract" and args.stage is None:
        parser.error("--stage is required for %s" % args.command)
    if args.command == "write":
        written = write(args.stage)
        print("wrote %d YAML files under %s" % (len(written), OBSERVER_CONFIG_DIR.as_posix()))
        return 0
    if args.command == "count":
        return count(args.stage)
    if args.command == "run":
        return run(args.stage, args.family, args.workers, args.allow_drift)
    if args.command == "baselines":
        return run_baselines(args.stage, args.workers or default_workers(), args.allow_drift)
    if args.command == "status":
        return status(args.stage)
    return contract(args.workers or 1)


if __name__ == "__main__":
    raise SystemExit(main())
